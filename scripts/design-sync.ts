/**
 * Copies and transforms design inputs (design/, read-only) into packages and apps.
 * Re-run after design files change: `pnpm design:sync`. Output is deterministic.
 */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';

import { legalMarkdown } from './legal';

const ROOT = join(import.meta.dirname, '..');
const DESIGN = join(ROOT, 'design');
const HEADER = '// GENERATED by scripts/design-sync.ts from design/. Do not edit.\n';

type ThemeValue = { light: string; dark: string };
type ColorToken = { name: string; value: ThemeValue };
type TypeStyle = {
  name: string;
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  letterSpacing?: string;
};
type Tokens = {
  color: { tokens: ColorToken[] };
  type: { groups: { name: string; family: 'sans' | 'thai'; styles: TypeStyle[] }[] };
  spacing: { tokens: { name: string; value: string }[] };
  radius: { tokens: { name: string; value: string }[] };
  layout: { tokens: { name: string; value: string }[] };
  motion: { tokens: { name: string; value: string }[] };
};

const camel = (name: string) => name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const px = (v: string) => Number(v.replace(/(px|ms)$/, ''));

function write(path: string, content: string) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

function copyDir(from: string, to: string, filter?: (file: string) => boolean) {
  rmSync(to, { recursive: true, force: true });
  mkdirSync(to, { recursive: true });
  for (const file of readdirSync(from).sort()) {
    if (filter && !filter(file)) continue;
    cpSync(join(from, file), join(to, file));
  }
}

// Only 400/600/700 TTFs are bundled (plan: 6 files). 500 (caption) maps to SemiBold.
const FONT_FAMILY: Record<'sans' | 'thai', Record<number, string>> = {
  sans: {
    400: 'BeVietnamPro-Regular',
    500: 'BeVietnamPro-SemiBold',
    600: 'BeVietnamPro-SemiBold',
    700: 'BeVietnamPro-Bold',
  },
  thai: { 400: 'Prompt-Regular', 500: 'Prompt-SemiBold', 600: 'Prompt-SemiBold', 700: 'Prompt-Bold' },
};

function syncTokens(tokens: Tokens) {
  const colors = { light: {} as Record<string, string>, dark: {} as Record<string, string> };
  for (const t of tokens.color.tokens) {
    colors.light[camel(t.name)] = t.value.light;
    colors.dark[camel(t.name)] = t.value.dark;
  }

  const typography: Record<string, object> = {};
  const typographyTh: Record<string, object> = {};
  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      const fontFamily = FONT_FAMILY[group.family][s.fontWeight];
      if (!fontFamily) throw new Error(`No font file for ${group.family} ${s.fontWeight}`);
      const style = {
        fontFamily,
        fontSize: px(s.fontSize),
        lineHeight: px(s.lineHeight),
        letterSpacing: s.letterSpacing ? px(s.letterSpacing) : 0,
      };
      if (s.name.startsWith('th-')) typographyTh[camel(s.name.slice(3))] = style;
      else typography[camel(s.name)] = style;
    }
  }

  const numeric = (list: { name: string; value: string }[], strip = '') =>
    Object.fromEntries(list.map((t) => [camel(t.name.replace(strip, '')), px(t.value)]));

  const json = (v: unknown) => JSON.stringify(v, null, 2);
  const out = `${HEADER}
export const colors = ${json(colors)} as const;

export type ColorName = keyof typeof colors.light;
export type Colors = Record<ColorName, string>;

export const typography = ${json(typography)} as const;

/** Thai overrides (th-*): same keys as \`typography\` where defined. */
export const typographyTh = ${json(typographyTh)} as const;

export type TypographyName = keyof typeof typography;

export const space = ${json(numeric(tokens.spacing.tokens, 'space-'))} as const;

export const radius = ${json(numeric(tokens.radius.tokens, 'radius-'))} as const;

export const layout = ${json(numeric(tokens.layout.tokens))} as const;

export const motion = ${json(numeric(tokens.motion.tokens))} as const;
`;
  write(join(ROOT, 'packages/ui/src/generated/tokens.ts'), out);
  return tokens.color.tokens;
}

/**
 * SVGs are drawn with light-theme token hex values. Each hex is swapped for its token so the
 * illustration follows the active theme. When several tokens share a light value, a fixed token
 * (same in both themes, e.g. mascot-face) wins so the light rendering stays identical.
 */
function syncSvgs(colorTokens: ColorToken[]) {
  const byHex = new Map<string, string>();
  // Illustrations are mascot/onboarding art, so mascot-face beats on-accent for the shared hex.
  const rank = (t: ColorToken) =>
    t.name === 'mascot-face' ? 0 : t.value.light === t.value.dark ? 1 : 2;
  const sorted = [...colorTokens].sort((a, b) => rank(a) - rank(b));
  for (const t of sorted) {
    const hex = t.value.light.toLowerCase();
    if (!byHex.has(hex)) byHex.set(hex, camel(t.name));
  }

  const entries: string[] = [];
  for (const dir of ['mascot', 'onboarding']) {
    for (const file of readdirSync(join(DESIGN, 'assets', dir)).sort()) {
      if (!file.endsWith('.svg')) continue;
      const svg = readFileSync(join(DESIGN, 'assets', dir, file), 'utf8').trim();
      const templated = svg
        .replace(/`/g, '\\`')
        .replace(/#[0-9a-fA-F]{6}\b/g, (hex) => {
          const token = byHex.get(hex.toLowerCase());
          return token ? `\${c.${token}}` : hex;
        });
      entries.push(`  '${basename(file, '.svg')}': (c: Colors) => \`${templated}\`,`);
    }
  }
  const out = `${HEADER}import type { Colors } from './tokens';

export const svgs = {
${entries.join('\n')}
} as const;

export type SvgName = keyof typeof svgs;
`;
  write(join(ROOT, 'packages/ui/src/generated/svgs.ts'), out);
}

type JsonObject = { [key: string]: unknown };
const isObject = (v: unknown): v is JsonObject => typeof v === 'object' && v !== null && !Array.isArray(v);

function deepMerge(base: JsonObject, over: JsonObject): JsonObject {
  const out: JsonObject = { ...base };
  for (const [k, v] of Object.entries(over)) {
    const current = out[k];
    out[k] = isObject(current) && isObject(v) ? deepMerge(current, v) : v;
  }
  return out;
}

/** design/i18n + packages/i18n/overrides (keys added or corrected during development). */
function syncI18n() {
  for (const ns of ['common', 'nuni', 'fourpop']) {
    for (const lang of ['en', 'vi', 'th']) {
      const base = JSON.parse(readFileSync(join(DESIGN, 'i18n', ns, `${lang}.json`), 'utf8')) as JsonObject;
      const overridePath = join(ROOT, 'packages/i18n/overrides', ns, `${lang}.json`);
      const merged = existsSync(overridePath)
        ? deepMerge(base, JSON.parse(readFileSync(overridePath, 'utf8')) as JsonObject)
        : base;
      write(
        join(ROOT, 'packages/i18n/src/locales', ns, `${lang}.json`),
        `${JSON.stringify(merged, null, 2)}\n`,
      );
    }
  }
}

type ManifestJson = {
  packs: { id: string; items: { id: string; image: string; thumbnail?: string }[] }[];
};

function syncContent() {
  const contentRoot = join(ROOT, 'packages/content');
  copyDir(join(DESIGN, 'assets/frames/base'), join(contentRoot, 'assets/frames/base'), (f) =>
    f.endsWith('.png'),
  );
  copyDir(join(DESIGN, 'assets/stickers/base'), join(contentRoot, 'assets/stickers/base'), (f) =>
    f.endsWith('.png'),
  );

  const manifestRaw = readFileSync(join(DESIGN, 'assets/manifest.json'), 'utf8');
  const manifest = JSON.parse(manifestRaw) as ManifestJson;
  write(
    join(contentRoot, 'src/generated/manifest.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );

  // Static require() map: Metro needs literal paths.
  const paths = new Set<string>();
  for (const pack of manifest.packs) {
    for (const item of pack.items) {
      paths.add(item.image);
      if (item.thumbnail) paths.add(item.thumbnail);
    }
  }
  const lines = [...paths]
    .sort()
    .map((p) => `  '${p}': require('../../assets/${p}'),`);
  write(
    join(contentRoot, 'src/generated/bundledAssets.ts'),
    `${HEADER}/** Manifest image path (relative to design/assets) → bundled asset module. */
export const bundledAssets: Record<string, number> = {
${lines.join('\n')}
};
`,
  );

  const legal = (['terms', 'privacy'] as const).map((doc) => {
    const md = legalMarkdown(doc);
    return `export const ${doc}En = ${JSON.stringify(md)};`;
  });
  // Open-source notices (A13/B13 licenses): bundled fonts (OFL) and Phosphor icons (MIT).
  const notices = [
    ['Be Vietnam Pro', join(ROOT, 'packages/ui/fonts/OFL-BeVietnamPro.txt')],
    ['Prompt', join(ROOT, 'packages/ui/fonts/OFL-Prompt.txt')],
    ['Phosphor Icons', join(ROOT, 'node_modules/phosphor-react-native/LICENSE')],
  ]
    .map(([name, file]) => `## ${name}\n\n\`\`\`\n${readFileSync(file!, 'utf8').trim()}\n\`\`\``)
    .join('\n\n');
  legal.push(`export const licensesEn = ${JSON.stringify(`# Open source licenses\n\n${notices}\n`)};`);
  write(join(contentRoot, 'src/generated/legal.ts'), `${HEADER}\n${legal.join('\n\n')}\n`);
}

function syncAppIcons() {
  for (const app of ['nuni', 'fourpop']) {
    const appDir = join(ROOT, 'apps', app);
    try {
      readdirSync(appDir);
    } catch {
      continue; // app not scaffolded yet
    }
    for (const variant of ['light', 'dark', 'tinted']) {
      const file = `${app}-icon-1024-${variant}.png`;
      mkdirSync(join(appDir, 'assets/icon'), { recursive: true });
      cpSync(join(DESIGN, 'assets/app-icons', file), join(appDir, 'assets/icon', `${variant}.png`));
    }
  }
}

const tokens = JSON.parse(readFileSync(join(DESIGN, 'tokens.json'), 'utf8')) as Tokens;
const colorTokens = syncTokens(tokens);
syncSvgs(colorTokens);
syncI18n();
syncContent();
syncAppIcons();
console.log('design:sync done');
