/**
 * Turns drizzle-kit output (drizzle/<app>/*.sql + meta/_journal.json) into src/<app>/migrations.ts
 * with the SQL inlined, so apps need no Babel/Metro setup for .sql imports.
 * Run via `pnpm --filter @nf/db db:generate`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');

type Journal = { entries: { idx: number; tag: string }[] };

for (const app of ['nuni', 'fourpop']) {
  const dir = join(ROOT, 'drizzle', app);
  const journal = JSON.parse(readFileSync(join(dir, 'meta/_journal.json'), 'utf8')) as Journal;
  const migrations = journal.entries.map((e) => {
    const key = `m${String(e.idx).padStart(4, '0')}`;
    const sql = readFileSync(join(dir, `${e.tag}.sql`), 'utf8');
    return `    ${key}: ${JSON.stringify(sql)},`;
  });
  const out = `// GENERATED by packages/db/scripts/bundle-migrations.ts from drizzle/${app}. Do not edit.
import type { MigrationBundle } from '../migrate';

const bundle: MigrationBundle = {
  journal: ${JSON.stringify(journal)},
  migrations: {
${migrations.join('\n')}
  },
};

export default bundle;
`;
  writeFileSync(join(ROOT, 'src', app, 'migrations.ts'), out);
  console.log(`${app}: ${journal.entries.length} migration(s)`);
}
